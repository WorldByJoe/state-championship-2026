# build_background.py · v1.1 · 2026-10-12
# Stitch the two NAIP aerial halves into aerial_data.js, and fetch a coarse
# 30 m DEM plus a 12 m aerial of the surrounding 36 x 24 km so the horizon
# (the mountains around the course) exists in the ride view.
# CHANGED: v1.1 image requests use the DEM's own projection (was fixed to UTM 13N) and retry
#   when the server sends an error page; NAIP fetched in <= 1000 px chunks (big requests time out).
#   v1.0 fetches the NAIP halves itself when they are not beside it.
import json, os, sys, subprocess, base64, struct, zlib, io
import numpy as np, rasterio
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); os.chdir(HERE)
info = json.load(open('course_info.json')); SR = info['epsg']
def fetch(url, out, tries=4):
    """curl a USGS image request, retrying when the server answers with an HTML error page."""
    for k in range(tries):
        subprocess.run(['curl', '-s', '--max-time', '300', '-o', out, url])
        head = open(out, 'rb').read(4) if os.path.exists(out) else b''
        if head[:2] == b'\xff\xd8' or head[:2] in (b'II', b'MM'): return
        print('retry', k + 1, out)
    raise SystemExit('image request failed: ' + out)

E0, N1, W, H = info['origin_e'], info['origin_n'], info['width'], info['height']

def naip_mosaic(x0, y0, x1, y1, res, out, quality=85, chunk=1000):
    """NAIP over a box (map units of SR) at res m/px, fetched in chunks of <= chunk px (big requests time out), stitched."""
    pw, ph = round((x1 - x0) / res), round((y1 - y0) / res); nx, ny = -(-pw // chunk), -(-ph // chunk)
    im = Image.new('RGB', (pw, ph))
    for i in range(nx):
        for j in range(ny):
            c0, c1 = i * pw // nx, (i + 1) * pw // nx; r0, r1 = j * ph // ny, (j + 1) * ph // ny
            bx0, bx1 = x0 + c0 * res, x0 + c1 * res; by1, by0 = y1 - r0 * res, y1 - r1 * res
            url = ('https://imagery.nationalmap.gov/arcgis/rest/services/USGSNAIPPlus/ImageServer/exportImage?'
                   f'bbox={bx0},{by0},{bx1},{by1}&bboxSR={SR}&imageSR={SR}&size={c1 - c0},{r1 - r0}&format=jpg&compressionQuality={quality}&f=image')
            fetch(url, '/tmp/naip_chunk.jpg', tries=2); im.paste(Image.open('/tmp/naip_chunk.jpg').convert('RGB'), (c0, r0))
    im.save(out, quality=quality); return im

# --- course aerial: NAIP at 0.6 m over the clip, embedded in aerial_data.js
im = Image.open('aerial_course.jpg') if os.path.exists('aerial_course.jpg') else naip_mosaic(E0, N1 - H, E0 + W, N1, 0.6, 'aerial_course.jpg', quality=82)   # fetch_naip.py may have written it
b = open('aerial_course.jpg', 'rb').read()
with open('aerial_data.js', 'w') as f:
    f.write('// aerial_data.js · generated by build_background.py v1.1 · USGS NAIP Plus orthoimagery, 0.6 m\n')
    f.write('window.AERIAL_JPG = "data:image/jpeg;base64,' + base64.b64encode(b).decode() + '";\n')
print('aerial_course.jpg', im.size, '%.1f MB' % (len(b) / 1e6))

# --- surroundings
cx, cy = E0 + W / 2, N1 - H / 2
bw, bh, res = 36000, 24000, 30
bbox = (cx - bw / 2, cy - bh / 2, cx + bw / 2, cy + bh / 2)
cols, rows = bw // res, bh // res
url = ('https://elevation.nationalmap.gov/arcgis/rest/services/3DEPElevation/ImageServer/exportImage?'
       f'bbox={bbox[0]},{bbox[1]},{bbox[2]},{bbox[3]}&bboxSR={SR}&imageSR={SR}&size={cols},{rows}'
       '&format=tiff&pixelType=F32&noData=-9999&interpolation=RSP_BilinearInterpolation&f=image')
fetch(url, 'background_dem_30m.tif')
with rasterio.open('background_dem_30m.tif') as d:
    z = d.read(1).astype(np.float32); tr = d.transform
    print('bg dem', z.shape, d.crs, tr.a, 'origin %.0f %.0f' % (tr.c, tr.f), 'range %.0f..%.0f' % (z[z > -1000].min(), z[z > -1000].max()))
z[z < -1000] = np.nan; z = np.where(np.isnan(z), np.nanmin(z), z)
z0 = int(np.floor(z.min())); q = np.round((z - z0) * 10).astype(np.uint16); assert q.max() < 65535
rgb = np.zeros((rows, cols, 3), np.uint8); rgb[..., 0] = q >> 8; rgb[..., 1] = q & 255
def png(a):
    raw = b''.join(b'\x00' + a[i].tobytes() for i in range(a.shape[0]))
    def chunk(t, d): return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', a.shape[1], a.shape[0], 8, 2, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b'')
p = png(rgb)
try: naip_mosaic(bbox[0], bbox[1], bbox[2], bbox[3], 12, 'background_aerial.jpg', quality=80)
except SystemExit:   # USGS image service down: same NAIP from Planetary Computer
    subprocess.run([sys.executable, 'fetch_naip.py', 'background', *map(str, bbox), '12', 'background_aerial.jpg'], check=True)
bj = open('background_aerial.jpg', 'rb').read(); print('bg aerial %.1f MB' % (len(bj) / 1e6), Image.open('background_aerial.jpg').size)
bginfo = dict(origin_e=tr.c, origin_n=tr.f, width=cols, height=rows, res=res, z0=z0,
              source='USGS 3DEP seamless DEM (1/3 arc-second) resampled to 30 m; NAIP Plus aerial at 12 m')
with open('background_data.js', 'w') as f:
    f.write('// background_data.js · generated by build_background.py v1.0 · 2026-10-06\n')
    f.write('window.BG_INFO = ' + json.dumps(bginfo) + ';\n')
    f.write('window.BG_HEIGHTS_PNG = "data:image/png;base64,' + base64.b64encode(p).decode() + '";\n')
    f.write('window.BG_AERIAL_JPG = "data:image/jpeg;base64,' + base64.b64encode(bj).decode() + '";\n')
print('background_data.js %.1f MB' % (os.path.getsize('background_data.js') / 1e6))
